from __future__ import annotations

from html import escape

from portrait_bot.config import Settings


def operator_details(settings: Settings) -> str:
    details = [
        escape(settings.operator_name),
        f"ИНН {escape(settings.operator_inn)}, ОГРНИП {escape(settings.operator_ogrnip)}",
    ]
    if settings.operator_address.strip():
        details.append(f"Адрес: {escape(settings.operator_address)}")
    details.append(f"Email: {escape(settings.support_email)}")
    return "\n".join(details)


