    support = support.lstrip("@")
    return (
        "‼️ После оплаты, чек отправляем\n"
        "строго менеджеру\n"
        f"@{manager} ‼️\n\n"
        f"💰 Цена за 1 стикер: <b>{price} руб.</b>\n"
        "Умножьте на нужное количество\n"
        "стикеров и оплатите точную сумму до копейки.\n\n"
        "Отсканируйте QR код для оплаты.\n\n"
        "Если требует КПП - 000000000\n"
        "Назначение платежа: Оплата за услугу\n\n"
        "После оплаты отправьте сюда:\n"
        f"@{manager}\n"
        "1. Чек\n"
        "2. Ваше ФИО\n"
        "3. Ваш номер телефона\n\n"
        f"администратору @{support}"
    )
